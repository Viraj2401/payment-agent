"""Generates sample_conversations.md from real agent runs.

Each transcript below is produced by actually running the Agent against
the live API (LLM extraction on if a key is configured), so the document
always reflects real behavior rather than hand-written examples.

Usage:
    python evals/generate_transcripts.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agent import Agent  # noqa: E402

CONVERSATIONS = [
    (
        "1. Successful end-to-end payment (messy, conversational inputs)",
        "ACC1001 / partial payment of ₹500 / casual confirmation phrasing.",
        [
            "Hi",
            "yeah my account number is ACC 1001 I think",
            "my name is Nithin Jain",
            "I was born on 14th May 1990",
            "can I do 500 for now?",
            "the card number is 4532 0151 1283 0366, name on card is Nithin Jain",
            "expires December 2027",
            "CVV is one two three",
            "sure, go ahead and charge it",
        ],
    ),
    (
        "2. Verification failure — user exhausts retries",
        "Wrong name once, then two wrong secondary factors. The agent locks the "
        "session and never reveals any account data.",
        [
            "Hi",
            "ACC1001",
            "my name is Nithin Jane",
            "Nithin Jain",
            "DOB is 1991-01-01",
            "Aadhaar last 4 is 9999",
            "hello? can we try again",
        ],
    ),
    (
        "3. Payment failure — expired card, then invalid card numbers",
        "Client-side validation rejects bad card data with clear guidance and a "
        "strike limit; nothing invalid ever reaches the payment API.",
        [
            "Hi",
            "ACC1001",
            "Nithin Jain",
            "1990-05-14",
            "pay 100",
            "card 4532015112830366, Nithin Jain on the card, cvv 123",
            "01/2020",
            "4532015112830367",
            "4532015112830367",
        ],
    ),
    (
        "4. Edge cases — out-of-order info, leap-year DOB, full amount, cancel at confirm",
        "Everything volunteered in one message (steps still happen in order "
        "internally), DOB 1988-02-29 is correctly accepted as a valid leap-year "
        "date, and the user cancels at the confirmation step — nothing is charged.",
        [
            "Hi, I'm Rahul Mehta, account ACC1004, born 29 Feb 1988",
            "just clear the full amount",
            "card number 4111 1111 1111 1111, Rahul Mehta on the card, expiry 11/2028, cvv 456",
            "actually no, cancel this",
        ],
    ),
]


def main() -> None:
    out = [
        "# Sample Conversations",
        "",
        "Generated by `python evals/generate_transcripts.py` — every transcript",
        "is a real run of the agent (live API; LLM extraction "
        + ("ON" if os.getenv("GEMINI_API_KEY", "") not in ("", "your-key-here") else "OFF")
        + ").",
        "",
    ]
    for title, blurb, turns in CONVERSATIONS:
        agent = Agent()
        out += [f"## {title}", "", f"_{blurb}_", "", "```"]
        for t in turns:
            reply = agent.next(t)["message"]
            out.append(f"User:  {t}")
            out.append(f"Agent: {reply}")
            out.append("")
        out += ["```", ""]

    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "sample_conversations.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
